// Emit the settings review inventory: every setting, where it lives now, its current
// tier, and a first-pass recommendation. Regenerate any time the schema changes.
const fs=require('fs'), vm=require('vm'), path=require('path');
const ROOT=process.argv[2];
global.window=global;
global.document={getElementById:()=>null,createElement:()=>({style:{},classList:{add(){},remove(){}},appendChild(){},textContent:''}),head:{appendChild(){}},body:{appendChild(){}},addEventListener(){}};
vm.runInThisContext(fs.readFileSync(path.join(ROOT,'js/constants.js'),'utf8'),{filename:'c.js'});
vm.runInThisContext(fs.readFileSync(path.join(ROOT,'js/world-settings-ui.js'),'utf8'),{filename:'ws.js'});
const WS=vm.runInThisContext('WORLD_SETTINGS');
const S=WS.SETTINGS, TABS=WS.TABS;

// ── First-pass recommendation rules ────────────────────────────────────────────
// The point is a defensible starting line for Kevin to redline, not a guess per row.
// A row is ADVANCED if it is a numeric tuning knob behind a working default, a
// developer overlay, or a designer lock. It is BASIC if it turns a feature on/off or
// picks a mode a level-designer thinks about up front.
const ADV_GROUP=[/^Weapon · /, /^Multiplayer Boss Scaling$/, /^Designer Locks$/, /^Wayfinding$/, /^Retreating Mobs$/, /^Spider Webs$/, /^Pack$/];
const BASIC_KEY=new Set(['sprintEnabled','autoStepUp','airJumpEnabled','jumpAttack','platformerEmeralds','platformerScore','backgroundTheme','worldZoom','dayCycleMinutes','nightSpawnBoost','fullMoonHpBoost','playersPassThrough','companionTeleport','physicsGravity','jumpHeightBlocks']);
function recommend(r){
  if (BASIC_KEY.has(r.key)) return ['basic','feature on/off or an up-front design choice'];
  if (r.tab==='debug') return ['advanced','developer overlay — not player-facing'];
  if (ADV_GROUP.some(re=>re.test(r.group||''))) return ['advanced','fine-tuning group behind a working default'];
  if (r.sub && r.dependsOn) return ['advanced','child knob of a toggle above it'];
  if (r.type==='cycle' && /Speed|Rate|Range|Accel|Lift|Force|Multiplier|Amount|Points|Bonus|Cooldown|Damage|Chance|Distance|Delay|Duration/i.test(r.label||'')) return ['advanced','numeric tuning of an already-working default'];
  if (r.type==='toggle') return ['basic','a feature switch a designer decides deliberately'];
  return ['basic','picks a mode/behaviour rather than tuning it'];
}
const MODE_LABEL={normal:'NRM',platformer:'PLT',speedrunner:'RUN',arena:'ARN',sandbox:'SBX'};
const out=[]; let changed=0;
out.push('# Settings review — 2D (side-scroll)\n');
out.push('Generated by `tools/gen-settings-review.js` from `js/world-settings-ui.js`. **Edit the');
out.push('`Your call` column** (leave blank to accept the recommendation) and note any regroup in');
out.push('`Move to`. Regenerate to pick up schema changes; your columns are the review record.\n');
out.push('`Now` / `Rec` = basic or **ADV**. `Δ` marks rows where the recommendation differs from today.');
out.push('Modes: NRM Normal · PLT Platformer · RUN Speed Run · ARN Arena · SBX Sandbox.');
out.push('\nAdvanced is now **sandbox-only** — players never see an ADV row, so anything marked ADV is');
out.push('invisible outside the world editor. That raises the stakes on wrongly marking something ADV.\n');
for(const t of TABS){
  const rows=S.filter(r=>r.tab===t.id);
  if(!rows.length) continue;
  out.push(`\n## ${t.label} \`${t.id}\` — ${rows.length} settings\n`);
  const groups=[...new Set(rows.map(r=>r.group||'-'))];
  for(const g of groups){
    const gr=rows.filter(r=>(r.group||'-')===g);
    out.push(`\n### ${g} (${gr.length})\n`);
    out.push('| Setting | Key | Modes | Now | Rec | Δ | Why | Your call | Move to |');
    out.push('|---|---|---|---|---|:-:|---|---|---|');
    for(const r of gr){
      const [rec,why]=recommend(r);
      const now=r.advanced?'**ADV**':'basic';
      const recS=rec==='advanced'?'**ADV**':'basic';
      const delta=((r.advanced?'advanced':'basic')!==rec);
      if(delta) changed++;
      const modes=(r.modes||[]).map(m=>MODE_LABEL[m]||m).join(' ');
      const label=(r.label||r.key).replace(/\|/g,'\\|');
      out.push(`| ${label}${r.sub?' ·sub':''} | \`${r.key}\` | ${modes} | ${now} | ${recS} | ${delta?'⚠':''} | ${why} | | |`);
    }
  }
}
const advNow=S.filter(r=>r.advanced).length;
const advRec=S.filter(r=>recommend(r)[0]==='advanced').length;
out.splice(8,0,`\n**Totals:** ${S.length} settings · advanced today **${advNow}** → recommended **${advRec}** · ${changed} rows would change (⚠).\n`);
fs.writeFileSync(path.join(ROOT,'docs/settings-review-2d.md'),out.join('\n')+'\n');
// CSV for bulk editing in a spreadsheet.
const csv=['tab,group,label,key,modes,current_tier,recommended_tier,changes,why,your_call,move_to'];
for(const r of S){const [rec,why]=recommend(r);
  csv.push([r.tab,r.group,r.label,r.key,(r.modes||[]).join(' '),r.advanced?'advanced':'basic',rec,((r.advanced?'advanced':'basic')!==rec)?'YES':'',why,'',''].map(v=>`"${String(v==null?'':v).replace(/"/g,'""')}"`).join(','));}
fs.writeFileSync(path.join(ROOT,'docs/settings-review-2d.csv'),csv.join('\n')+'\n');
console.log(`2D: ${S.length} settings, advanced ${advNow} -> ${advRec}, ${changed} changes flagged`);

// ── Overhead ───────────────────────────────────────────────────────────────────
// No schema to read: the panel is hand-written HTML, so parse the render template.
// (Converting it to a schema is the proposed follow-up; until then this keeps the
// review list honest rather than hand-maintained.)
{
  const src=fs.readFileSync(path.join(ROOT,'js/overhead/overhead-settings.js'),'utf8');
  const body=src.slice(src.indexOf('_render()'));
  const rows=[]; let group='(ungrouped)';
  const re=/<h3>([^<]+)<\/h3>|\$\{(range|sel|toggle)\('([^']+)',\s*'((?:[^'\\]|\\.)*)'/g;
  let m;
  while((m=re.exec(body))){
    if(m[1]){ group=m[1].replace(/&amp;/g,'&').trim(); continue; }
    rows.push({group,kind:m[2],key:m[3],label:m[4].replace(/\\'/g,"'")});
  }
  const ADV_KEY=new Set(['elevOffset','jumpFloat','jumpScale','sprintMultiplier','crossbowSpeed','tridentSpeed','tridentReturnSpeed','boomerangSpeed','boomerangRange','boomerangWidth','meleeReach','meleeArcDeg','detectionRange','interactionZoom','interactionSpeed','lampBrightness','glowReach','shadowDarkness','lavaDamage','weightThreshold']);
  function recOH(r){
    if(ADV_KEY.has(r.key)) return ['advanced','numeric tuning of a working default'];
    if(r.kind==='toggle') return ['basic','a feature switch a designer decides deliberately'];
    if(r.kind==='sel') return ['basic','picks a mode/behaviour rather than tuning it'];
    return ['advanced','slider fine-tuning behind a working default'];
  }
  const o=[];
  o.push('# Settings review — Overhead (top-down)\n');
  o.push('Generated by `tools/gen-settings-review.js`, parsed from `OH_WORLD_SETTINGS._render()`');
  o.push('in `js/overhead/overhead-settings.js` — the overhead panel has **no schema**, so there is');
  o.push('nowhere to store a tier or help text today. Same review method as the 2D list: fill');
  o.push('`Your call`, note regroups in `Move to`.\n');
  o.push('There is **no advanced tier in overhead yet** — the `Rec` column is a proposal, and');
  o.push('adopting it means converting this panel to a schema like the 2D one (which also gives it');
  o.push('per-setting help text, and makes the user guide generatable).\n');
  const advRec=rows.filter(r=>recOH(r)[0]==='advanced').length;
  o.push(`**Totals:** ${rows.length} settings in ${new Set(rows.map(r=>r.group)).size} groups · recommended advanced **${advRec}**, basic **${rows.length-advRec}**.\n`);
  for(const g of [...new Set(rows.map(r=>r.group))]){
    const gr=rows.filter(r=>r.group===g);
    o.push(`\n## ${g} (${gr.length})\n`);
    o.push('| Setting | Key | Control | Rec | Why | Your call | Move to |');
    o.push('|---|---|---|---|---|---|---|');
    for(const r of gr){
      const [rec,why]=recOH(r);
      o.push(`| ${r.label.replace(/\|/g,'\\|')} | \`${r.key}\` | ${r.kind} | ${rec==='advanced'?'**ADV**':'basic'} | ${why} | | |`);
    }
  }
  fs.writeFileSync(path.join(ROOT,'docs/settings-review-overhead.md'),o.join('\n')+'\n');
  const csv=['group,label,key,control,recommended_tier,why,your_call,move_to'];
  for(const r of rows){const [rec,why]=recOH(r);
    csv.push([r.group,r.label,r.key,r.kind,rec,why,'',''].map(v=>`"${String(v==null?'':v).replace(/"/g,'""')}"`).join(','));}
  fs.writeFileSync(path.join(ROOT,'docs/settings-review-overhead.csv'),csv.join('\n')+'\n');
  console.log(`overhead: ${rows.length} settings parsed, recommended advanced ${advRec}`);
}
